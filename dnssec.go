package cloudns

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net/http"
	"strings"
	"time"

	"github.com/go-resty/resty/v2"
)

// DNSSECDSRecord contains the parameters needed to publish a DS at the registrar.
// Numeric fields are strings, matching the ClouDNS API response.
type DNSSECDSRecord struct {
	KeyTag         string `json:"key_tag"`
	Algorithm      string `json:"algorithm"`
	AlgorithmName  string `json:"algorithm_name"`
	DigestType     string `json:"digest_type"`
	DigestTypeName string `json:"digest_type_name"`
	Digest         string `json:"digest"`
}

// DNSSECDetails describes signing state and records generated by ClouDNS.
// Disabled DNSSEC has Enabled=false and empty record slices.
type DNSSECDetails struct {
	Enabled   bool
	OptOut    bool
	DS        []string
	DSRecords []DNSSECDSRecord
	DNSKEY    []string
}

type dnssecRequest struct {
	Apiaccess
	Domain string `json:"domain-name"`
	Status *int   `json:"status,omitempty"`
}

func (z Zone) dnssecRequest(ctx context.Context, a *Apiaccess, path string, status *int) ([]byte, error) {
	if a == nil {
		return nil, errors.New("DNSSEC requires API credentials")
	}
	if strings.TrimSpace(z.Domain) == "" {
		return nil, errors.New("DNSSEC requires a domain name")
	}
	resp, err := resty.New().SetTransport(http.DefaultTransport).SetTimeout(30*time.Second).R().SetContext(ctx).
		SetHeader("Accept", "application/json").SetHeader("User-Agent", "github.com/ClouDNS/cloudns-go").
		SetBody(dnssecRequest{Apiaccess: *a, Domain: z.Domain, Status: status}).Post(apiurl + "/dns/" + path + ".json")
	if err != nil {
		return nil, fmt.Errorf("DNSSEC request: %w", err)
	}
	if resp.IsError() {
		return nil, fmt.Errorf("DNSSEC request returned HTTP %d", resp.StatusCode())
	}
	if !json.Valid(resp.Body()) {
		return nil, errors.New("invalid DNSSEC JSON response")
	}
	return resp.Body(), nil
}

// DNSSECAvailable checks whether DNSSEC is supported for this zone.
func (z Zone) DNSSECAvailable(ctx context.Context, a *Apiaccess) (bool, error) {
	body, err := z.dnssecRequest(ctx, a, "is-dnssec-available", nil)
	if err != nil {
		return false, err
	}
	if msg, failed := checkapierr(body); failed {
		return false, errors.New(msg)
	}
	return dnssecFlag(body)
}

func dnssecFlag(raw json.RawMessage) (bool, error) {
	switch strings.TrimSpace(string(raw)) {
	case "1", `"1"`, "true":
		return true, nil
	case "0", `"0"`, "false":
		return false, nil
	default:
		return false, errors.New("invalid DNSSEC boolean value")
	}
}

func (z Zone) dnssecChange(ctx context.Context, a *Apiaccess, path string, status *int) error {
	body, err := z.dnssecRequest(ctx, a, path, status)
	if err != nil {
		return err
	}
	var result apierr
	if err := json.Unmarshal(body, &result); err != nil {
		return fmt.Errorf("decode DNSSEC response: %w", err)
	}
	if result.Status != "Success" {
		if result.Desc != "" {
			return errors.New(result.Desc)
		}
		return errors.New("unexpected DNSSEC operation response")
	}
	return nil
}

// ActivateDNSSEC enables signing. Key generation may complete asynchronously.
func (z Zone) ActivateDNSSEC(ctx context.Context, a *Apiaccess) error {
	return z.dnssecChange(ctx, a, "activate-dnssec", nil)
}

// DeactivateDNSSEC disables signing. Remove parent DS records before calling it.
func (z Zone) DeactivateDNSSEC(ctx context.Context, a *Apiaccess) error {
	return z.dnssecChange(ctx, a, "deactivate-dnssec", nil)
}

// SetDNSSECOptOut enables or disables NSEC3 opt-out for an active signed zone.
func (z Zone) SetDNSSECOptOut(ctx context.Context, a *Apiaccess, enabled bool) error {
	status := 0
	if enabled {
		status = 1
	}
	return z.dnssecChange(ctx, a, "set-dnssec-optout", &status)
}

// DNSSEC returns the current signing state, DS/DNSKEY records and opt-out flag.
// Only the documented dnssec_not_active error is normalized to disabled state;
// authentication, missing-zone and other API errors are returned to the caller.
func (z Zone) DNSSEC(ctx context.Context, a *Apiaccess) (DNSSECDetails, error) {
	var details DNSSECDetails
	body, err := z.dnssecRequest(ctx, a, "get-dnssec-ds-records", nil)
	if err != nil {
		return details, err
	}
	var response struct {
		Status      json.RawMessage  `json:"status"`
		Description string           `json:"statusDescription"`
		OptOut      json.RawMessage  `json:"optout"`
		DS          []string         `json:"ds"`
		DSRecords   []DNSSECDSRecord `json:"ds_records"`
		DNSKEY      []string         `json:"dnskey"`
	}
	if err := json.Unmarshal(body, &response); err != nil {
		return details, fmt.Errorf("decode DNSSEC details: %w", err)
	}
	if string(response.Status) == `"Failed"` {
		if response.Description == "dnssec_not_active" {
			return details, nil
		}
		return details, fmt.Errorf("DNSSEC: %s", response.Description)
	}
	details.Enabled, err = dnssecFlag(response.Status)
	if err != nil {
		return details, err
	}
	if len(response.OptOut) > 0 {
		details.OptOut, err = dnssecFlag(response.OptOut)
		if err != nil {
			return DNSSECDetails{}, err
		}
	}
	if !details.Enabled {
		return DNSSECDetails{}, nil
	}
	details.DS, details.DSRecords, details.DNSKEY = response.DS, response.DSRecords, response.DNSKEY
	return details, nil
}
